"""Generate every table the paper prints, from the committed records.

    python tools/build_paper_results.py

Writes into paper/generated/. Nothing there is edited by hand and nothing
in the paper is typed by hand, so the prose cannot drift from the data.
Rerun after any completed run.

Refuses to emit a table from an incomplete record set, because a partial
run averaged into a column reports a benchmark that was not run.
"""

from __future__ import annotations

import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from legible_motion_bench import adapter, metrics, runner, world  # noqa: E402
from legible_motion_bench.observer import Observer  # noqa: E402
from legible_motion_bench.planners import ShortestPathPlanner  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "generated"
HEADLINE_CEILING = 1.25
BANNER = (
    "% Generated by tools/build_paper_results.py from results/*.jsonl and\n"
    "% configs/model_manifest.json. Do not edit by hand; rerun the tool\n"
    "% after any completed run.\n"
)


def load_groups(scenarios):
    """Complete record files, grouped by alias and cost ceiling."""
    groups = defaultdict(list)
    for path in sorted((ROOT / "results").glob("*.jsonl")):
        records = runner.load_records(path)
        if not records:
            continue
        answered = [r for r in records if runner.answered(r)]
        if len(answered) != len(scenarios):
            continue
        runner.require_complete(records, scenarios, str(path))
        first = records[0]
        groups[(first["run_alias"], first["cost_ceiling"], first.get("temperature"))].append(
            records
        )
    return groups


def score(scenarios, records, observer):
    by_id = {s.id: s for s in scenarios}
    out = []
    for record in records:
        if not runner.answered(record) or not record["parsed"]:
            out.append(None)
            continue
        out.append(
            metrics.evaluate(by_id[record["scenario_id"]], observer, record["waypoints"])
        )
    return out


def model_table(scenarios, groups, observer, baselines) -> str:
    """Counts per model at the headline ceiling, sampled runs only."""
    cells = {
        alias: runs
        for (alias, ceiling, temp), runs in groups.items()
        if ceiling == HEADLINE_CEILING and temp is not None and len(runs) >= 2
    }
    if not cells:
        return BANNER + "% no sampled runs at the headline ceiling yet\n"

    manifest = adapter.load_manifest()
    aliases = sorted(cells)
    rows = defaultdict(list)
    decodes = {}
    for alias in aliases:
        parsed = feasible = beat = over = keepout = claimed = total = 0
        for records in cells[alias]:
            for record, result in zip(records, score(scenarios, records, observer)):
                # Attempts are not decodes. A file carries a record for
                # every failed request too, and counting those would
                # inflate the denominator with our own rate limits.
                if not runner.answered(record):
                    continue
                total += 1
                if record.get("claimed_legible") is True:
                    claimed += 1
                if result is None:
                    continue
                parsed += 1
                if not result.feasible:
                    continue
                feasible += 1
                if result.legibility > baselines[record["scenario_id"]]:
                    beat += 1
                if result.cost_ratio > HEADLINE_CEILING + 1e-9:
                    over += 1
                if result.safety.keep_out_entries:
                    keepout += 1
        decodes[alias] = total
        rows["replies that parsed"].append(parsed)
        rows["called legible by the model"].append(claimed)
        rows["physically possible"].append(feasible)
        rows["clearer than the shortest path"].append(beat)
        rows["over the stated path budget"].append(over)
        rows["entered a keep-out zone"].append(keepout)

    order = [
        "replies that parsed",
        "called legible by the model",
        "physically possible",
        "clearer than the shortest path",
        "over the stated path budget",
        "entered a keep-out zone",
    ]
    counts = set(decodes.values())
    if len(counts) != 1:
        raise SystemExit(
            f"models were not asked the same number of times: {decodes}. "
            f"A shared column heading would be false."
        )
    header = " & ".join(
        [f"Over {counts.pop()} decodes each"]
        + [manifest.get(a, {}).get("display_name", a) for a in aliases]
    )
    lines = [
        BANNER,
        "\\begin{tabular}{l" + "r" * len(aliases) + "}",
        "\\toprule",
        header + " \\\\",
        "\\midrule",
    ]
    for label in order:
        lines.append(label + " & " + " & ".join(str(v) for v in rows[label]) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def ceiling_table(scenarios, groups, observer, baselines) -> str:
    """Median cost paid and budget violations, per model per ceiling."""
    sampled = {
        (alias, ceiling): runs
        for (alias, ceiling, temp), runs in groups.items()
        if temp is not None and len(runs) >= 2
    }
    aliases = sorted({a for a, _ in sampled})
    ceilings = sorted({c for _, c in sampled})
    if not aliases or len(ceilings) < 2:
        return BANNER + "% not enough ceilings swept yet\n"

    manifest = adapter.load_manifest()
    lines = [
        BANNER,
        "\\begin{tabular}{r" + "rr" * len(aliases) + "}",
        "\\toprule",
        "& "
        + " & ".join(
            f"\\multicolumn{{2}}{{c}}{{{manifest.get(a, {}).get('display_name', a)}}}"
            for a in aliases
        )
        + " \\\\",
        "Stated budget & " + " & ".join(["median cost & over"] * len(aliases)) + " \\\\",
        "\\midrule",
    ]
    for ceiling in ceilings:
        cells = []
        for alias in aliases:
            runs = sampled.get((alias, ceiling))
            if not runs:
                # A single hyphen, not "--". LaTeX sets "--" as an en
                # dash, which is not allowed anywhere in this project.
                cells.extend(["-", "-"])
                continue
            ratios, over = [], 0
            for records in runs:
                for record, result in zip(records, score(scenarios, records, observer)):
                    if result is None or not result.feasible:
                        continue
                    ratios.append(result.cost_ratio)
                    if result.cost_ratio > ceiling + 1e-9:
                        over += 1
            cells.append(f"{statistics.median(ratios):.4f}" if ratios else "-")
            cells.append(str(over))
        lines.append(f"{ceiling:.2f} & " + " & ".join(cells) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def manifest_table() -> str:
    manifest = adapter.load_manifest()
    lines = [
        BANNER,
        "\\begin{tabular}{lll}",
        "\\toprule",
        "Model & Run alias in records & API checkpoint \\\\",
        "\\midrule",
    ]
    for alias in sorted(manifest):
        entry = manifest[alias]
        display = entry.get("display_name", alias)
        api = entry["api_model"].replace("_", "\\_")
        lines.append(f"{display} & \\texttt{{{alias.replace('_', chr(92) + '_')}}} & \\texttt{{{api}}} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def main() -> int:
    scenarios = list(world.load_directory(ROOT / "scenarios"))
    observer = Observer(condition="geodesic")
    baselines = {
        s.id: metrics.evaluate(
            s, observer, ShortestPathPlanner().plan(s).points
        ).legibility
        for s in scenarios
    }
    groups = load_groups(scenarios)

    OUT.mkdir(parents=True, exist_ok=True)
    written = {
        "model_table.tex": model_table(scenarios, groups, observer, baselines),
        "ceiling_table.tex": ceiling_table(scenarios, groups, observer, baselines),
        "model_manifest.tex": manifest_table(),
    }
    for name, body in written.items():
        (OUT / name).write_text(body, encoding="utf-8", newline="\n")
        print(f"wrote paper/generated/{name} ({len(body.splitlines())} lines)")

    complete = sorted({f"{a} at {c}" for a, c, t in groups if t is not None})
    print(f"\nsampled cells with complete records: {len(complete)}")
    for cell in complete:
        print(f"  {cell}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
